"""android-xml adapter: values/strings.xml (base) + values-b+xx/strings.xml.

Output matches the conventions of the reference project: UTF-8, no XML
declaration, 4-space indent, `\\'` escaping, key order = strings.toml order.

Special keys policy ("skip and keep"): managed entries are plain translatable
<string> elements; everything else (translatable="false", <string-array>,
<plurals>, other resources) is invisible to import and survives build: the
file is rewritten, but special blocks from the existing file are appended
unchanged, including comments (parsed with TreeBuilder(insert_comments=True),
since plain xml.etree parsing would drop them).
"""
from __future__ import annotations

import xml.etree.ElementTree as ET
from pathlib import Path

from ..fsutil import atomic_write_text
from .base import Adapter

# raw text -> android resource text ('@'/'?' need escaping only at string start,
# handled separately in escape())
_ESCAPES = [
    ("\\", "\\\\"),   # must be first
    ("'", "\\'"),
    ('"', '\\"'),
    ("\n", "\\n"),
    ("\t", "\\t"),
]

_XML_ESCAPES = [("&", "&amp;"), ("<", "&lt;"), (">", "&gt;")]


def escape(text: str) -> str:
    for a, b in _XML_ESCAPES:
        text = text.replace(a, b)
    for a, b in _ESCAPES:
        text = text.replace(a, b)
    if text.startswith(("@", "?")):
        text = "\\" + text
    return text


def _parse(text: str) -> ET.Element:
    """Parse keeping comments as ET.Comment nodes (default parser drops them)."""
    parser = ET.XMLParser(target=ET.TreeBuilder(insert_comments=True))
    return ET.fromstring(text, parser=parser)


def _is_managed(node: ET.Element) -> bool:
    """Managed = plain translatable <string name=...>: regenerated by build,
    read by import. Everything else is a special key: skip and keep."""
    return (node.tag == "string" and bool(node.get("name"))
            and node.get("translatable") != "false")


def unescape(text: str) -> str:
    # XML entities are handled by the parser; undo android escapes.
    out = []
    i = 0
    while i < len(text):
        c = text[i]
        if c == "\\" and i + 1 < len(text):
            nxt = text[i + 1]
            mapping = {"n": "\n", "t": "\t", "'": "'", '"': '"', "\\": "\\", "@": "@", "?": "?"}
            if nxt in mapping:
                out.append(mapping[nxt])
                i += 2
                continue
        out.append(c)
        i += 1
    return "".join(out)


class AndroidXmlAdapter(Adapter):
    name = "android-xml"

    @property
    def res_dir(self) -> Path:
        rel = self.project.adapter_config.get("res_dir", "res")
        return (self.project.root / rel).resolve()

    @property
    def legacy_codes(self) -> dict[str, str]:
        return dict(self.project.adapter_config.get("legacy_codes", {}))

    def dir_for(self, lang: str) -> str:
        code = self.legacy_codes.get(lang, lang)
        return "values-b+" + code.replace("-", "+")

    def lang_for(self, dirname: str) -> str | None:
        if not dirname.startswith("values-b+"):
            return None
        code = dirname[len("values-b+"):].replace("+", "-")
        reverse = {v: k for k, v in self.legacy_codes.items()}
        return reverse.get(code, code)

    # --- export ----------------------------------------------------------

    def _preserved_blocks(self, path: Path) -> list[str]:
        """Serialized special keys from an existing file, in original order.
        A comment directly preceding a special block belongs to it; comments
        inside blocks come along with the parse. Comments before managed
        strings describe regenerated content and are dropped; trailing
        comments are kept."""
        if not path.is_file():
            return []
        root = _parse(path.read_text(encoding="utf-8"))
        blocks: list[str] = []
        pending: list[ET.Element] = []
        for node in root:
            if node.tag is ET.Comment:
                pending.append(node)
                continue
            if _is_managed(node):
                pending = []
                continue
            for n in (*pending, node):
                n.tail = None
                blocks.append("    " + ET.tostring(n, encoding="unicode"))
            pending = []
        for n in pending:  # trailing comments after the last element
            n.tail = None
            blocks.append("    " + ET.tostring(n, encoding="unicode"))
        return blocks

    def export(self, locales: dict[str, dict[str, dict]],
               langs: list[str] | None = None) -> list[str]:
        base = {key: {"text": e.text} for key, e in self.project.strings.items()}
        if langs is None:
            targets = [("values", base)] + [
                (self.dir_for(lang), locales.get(lang, {})) for lang in self.project.languages]
        else:  # incremental: selected languages only, base untouched
            targets = [(self.dir_for(lang), locales.get(lang, {})) for lang in langs]
        written = []
        for dirname, entries in targets:
            out_dir = self.res_dir / dirname
            path = out_dir / "strings.xml"
            preserved = self._preserved_blocks(path)
            lines = ["<resources>"]
            for key in self.project.strings:
                e = entries.get(key)
                if e and e.get("text"):
                    lines.append(f'    <string name="{key}">{escape(e["text"])}</string>')
            lines.extend(preserved)
            lines.append("</resources>")
            out_dir.mkdir(parents=True, exist_ok=True)
            atomic_write_text(path, "\n".join(lines) + "\n")
            written.append(str(path))
        return written

    # --- import ----------------------------------------------------------

    def import_(self) -> dict[str, dict[str, str]]:
        result: dict[str, dict[str, str]] = {}
        if not self.res_dir.is_dir():
            return result
        for d in sorted(self.res_dir.iterdir()):
            lang = self.lang_for(d.name) if d.is_dir() else None
            if lang is None or lang not in self.project.languages:
                continue
            f = d / "strings.xml"
            if not f.is_file():
                continue
            root = ET.fromstring(f.read_text(encoding="utf-8"))
            strings: dict[str, str] = {}
            for node in root:  # special keys (arrays, plurals, ...) are skipped
                if _is_managed(node):
                    strings[node.get("name")] = unescape("".join(node.itertext()))
            result[lang] = strings
        return result

    # --- bootstrap -------------------------------------------------------

    def bootstrap_source(self) -> tuple[dict[str, str], int]:
        from ..config import ConfigError

        f = self.res_dir / "values" / "strings.xml"
        if not f.is_file():
            raise ConfigError(f"bootstrap: base file not found: {f}")
        root = ET.fromstring(f.read_text(encoding="utf-8"))
        entries: dict[str, str] = {}
        skipped = 0
        for node in root:
            if _is_managed(node):
                entries[node.get("name")] = unescape("".join(node.itertext()))
            else:  # translatable="false", string-array, plurals, ...
                skipped += 1
        return entries, skipped

    # --- check -----------------------------------------------------------

    def check(self, text: str) -> list[str]:
        snippet = f"<resources><string name=\"x\">{escape(text)}</string></resources>"
        try:
            ET.fromstring(snippet)
        except ET.ParseError as e:
            return [f"escaped text is not valid XML: {e}"]
        return []
