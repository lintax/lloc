"""Bootstrap: generate strings.toml from an existing base platform file."""
from __future__ import annotations

import re
from pathlib import Path

from .fsutil import atomic_write_text

_BARE_KEY_RE = re.compile(r"[A-Za-z0-9_-]+")


def toml_escape(s: str) -> str:
    out = s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")
    out = "".join(c if c >= " " else f"\\u{ord(c):04X}" for c in out)
    return f'"{out}"'


def _toml_key(key: str) -> str:
    return key if _BARE_KEY_RE.fullmatch(key) else toml_escape(key)


def write_strings_toml(path: Path, entries: dict[str, str],
                       meta: dict[str, dict[str, str]] | None = None) -> None:
    """Write a strings.toml skeleton: text only; context/type are filled by
    hand later, unless the adapter could derive them (`meta`: key ->
    {"context": ..., "type": ...})."""
    meta = meta or {}
    lines = [
        "# Generated by `lloc import --bootstrap-strings`.",
        "# Add `context = \"...\"` and `type = \"button|title|message\"` to strings as needed.",
        "",
    ]
    for key, text in entries.items():
        lines.append(f"[{_toml_key(key)}]")
        lines.append(f"text = {toml_escape(text)}")
        for field in ("context", "type"):
            if meta.get(key, {}).get(field):
                lines.append(f"{field} = {toml_escape(meta[key][field])}")
        lines.append("")
    atomic_write_text(path, "\n".join(lines))
